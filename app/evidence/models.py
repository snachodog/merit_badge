"""Evidence a learner records against one requirement in one plan.

Private by design (PLAN.md 13.2): files live in the evidence storage, not
under any public path, and are served only by an owner-checked view.
"""
from django.conf import settings
from django.core.exceptions import ValidationError
from django.db import models

from learning.models import RequirementProgress


class EvidenceRecord(models.Model):
    class EvidenceType(models.TextChoices):
        NOTE = "note", "Note"
        TEXT_RESPONSE = "text_response", "Text response"
        FILE = "file", "File"
        IMAGE = "image", "Image"
        AUDIO = "audio", "Audio"
        VIDEO = "video", "Video"
        EXTERNAL_LINK = "external_link", "External link"
        TIME_LOG = "time_log", "Time log"
        WITNESS_RECORD = "witness_record", "Witness record"
        AI_PRACTICE_SUMMARY = "ai_practice_summary", "AI practice summary"
        OTHER = "other", "Other"

    FILE_TYPES = (EvidenceType.FILE, EvidenceType.IMAGE, EvidenceType.AUDIO, EvidenceType.VIDEO)

    class ReviewStatus(models.TextChoices):
        UNREVIEWED = "unreviewed", "Unreviewed"
        LEARNER_ATTESTED = "learner_attested", "Learner attested"
        FEEDBACK_RECEIVED = "feedback_received", "Feedback received"
        HUMAN_OBSERVED = "human_observed", "Human observed"

    class RetentionStatus(models.TextChoices):
        RETAINED = "retained", "Retained"
        REMOVAL_REQUESTED = "removal_requested", "Removal requested"

    progress = models.ForeignKey(
        RequirementProgress, on_delete=models.CASCADE, related_name="evidence_records"
    )
    created_by = models.ForeignKey(
        settings.AUTH_USER_MODEL, null=True, on_delete=models.SET_NULL, related_name="+"
    )
    evidence_type = models.CharField(max_length=24, choices=EvidenceType.choices)
    title = models.CharField(max_length=200, blank=True)
    description = models.TextField(blank=True)
    # File evidence. The key is generated by the server; it never contains user input.
    storage_key = models.CharField(max_length=300, blank=True)
    original_filename = models.CharField(max_length=200, blank=True)
    content_type = models.CharField(max_length=100, blank=True)
    size_bytes = models.PositiveBigIntegerField(null=True, blank=True)
    sha256 = models.CharField(max_length=64, blank=True)
    external_url = models.URLField(blank=True)
    review_status = models.CharField(
        max_length=20, choices=ReviewStatus.choices, default=ReviewStatus.UNREVIEWED
    )
    reviewer_name_or_label = models.CharField(max_length=200, blank=True)
    review_notes = models.TextField(blank=True)
    retention_status = models.CharField(
        max_length=20, choices=RetentionStatus.choices, default=RetentionStatus.RETAINED
    )
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["created_at", "id"]
        constraints = [
            models.CheckConstraint(
                name="evidence_human_observed_needs_label",
                condition=~models.Q(review_status="human_observed")
                | (
                    ~models.Q(reviewer_name_or_label="")
                    & ~models.Q(evidence_type="ai_practice_summary")
                ),
            )
        ]

    def __str__(self):
        return self.title or f"{self.get_evidence_type_display()} #{self.pk}"

    def clean(self):
        errors = {}
        if self.review_status == self.ReviewStatus.HUMAN_OBSERVED:
            if not self.reviewer_name_or_label.strip():
                errors["reviewer_name_or_label"] = (
                    "Human observed needs the name or label of the person who observed."
                )
            if self.evidence_type == self.EvidenceType.AI_PRACTICE_SUMMARY:
                errors["review_status"] = "An AI practice summary cannot be human observed."
        if self.evidence_type in self.FILE_TYPES and not self.storage_key:
            errors["storage_key"] = "File evidence needs a stored file."
        if self.evidence_type == self.EvidenceType.EXTERNAL_LINK and not self.external_url:
            errors["external_url"] = "A link record needs a URL."
        if errors:
            raise ValidationError(errors)

    def save(self, *args, **kwargs):
        self.clean()
        super().save(*args, **kwargs)
